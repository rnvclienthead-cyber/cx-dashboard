const _exact = Object.fromEntries(SYNC_CATALOG.map(s => [s.key, s]))

/**
 * Возвращает человеческое описание синка по «сырому» action из journal.
 * { label, desc, mp, known } — known=false, если название не найдено в справочнике.
 */
export function describeSync(action) {
  const raw = String(action || '').trim()
  if (!raw) return { label: '—', desc: '', mp: '', known: false }
  if (_exact[raw]) return { ...(_exact[raw]), known: true }
  for (const p of SYNC_PATTERNS) {
    if (p.re.test(raw)) return { label: p.label, desc: p.desc, mp: '', known: true }
  }
  return { label: raw, desc: '', mp: '', known: false }
}
