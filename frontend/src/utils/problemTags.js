export function tagIdsEqual(a, b) {
  const x = [...(a || [])].map(Number).sort((m, n) => m - n)
  const y = [...(b || [])].map(Number).sort((m, n) => m - n)
  return JSON.stringify(x) === JSON.stringify(y)
}
