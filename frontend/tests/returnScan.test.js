import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const scan = readFileSync(new URL('../src/views/ReturnScanView.vue', import.meta.url), 'utf8')
const returns = readFileSync(new URL('../src/views/ReturnsView.vue', import.meta.url), 'utf8')
const reship = readFileSync(new URL('../src/views/ReshipmentView.vue', import.meta.url), 'utf8')
const card = readFileSync(new URL('../src/views/ReturnCardView.vue', import.meta.url), 'utf8')

test('scanner asks the lookup API instead of guessing income_id', () => {
  assert.match(scan, /\/api\/return\/lookup\?code=/)
  assert.match(scan, /data\.kind === 'batch'/)
  assert.match(scan, /data\.item\?\.srid \|\| data\.item\?\.claim_id/)
})

test('scanner page is pistol plus intake, without camera or photo', () => {
  assert.match(scan, /formatManualCode/)
  assert.match(scan, /createHidWedge/)
  assert.match(scan, /keydown/)
  assert.match(scan, /не обязателен/)
  assert.match(scan, /\/api\/return\/intake/)
  assert.match(scan, /Сегодня на складе/)
  assert.match(scan, /isStickerQr/)
  assert.match(scan, /isLinearSticker/)
  assert.match(scan, /полоски штрихкода/)
  assert.doesNotMatch(scan, /getUserMedia/)
  assert.doesNotMatch(scan, /html5-qrcode/)
  assert.doesNotMatch(scan, /Фото наклейки/)
  assert.doesNotMatch(scan, /startCamera/)
  assert.doesNotMatch(scan, /ocrStickerPhoto/)
  assert.doesNotMatch(scan, /\/api\/return\/read-sticker/)
  assert.doesNotMatch(scan, /handleDetected\(qr\)/)
  assert.doesNotMatch(scan, /не поддерживает сканирование/)
  assert.doesNotMatch(scan, /Верхнее, напр/)
  assert.doesNotMatch(scan, /partA/)
})

test('scanner page is lazy-loaded so phones do not parse the whole dashboard', () => {
  const router = readFileSync(new URL('../src/router/index.js', import.meta.url), 'utf8')
  const html = readFileSync(new URL('../index.html', import.meta.url), 'utf8')
  const vite = readFileSync(new URL('../vite.config.js', import.meta.url), 'utf8')
  const app = readFileSync(new URL('../src/App.vue', import.meta.url), 'utf8')
  const main = readFileSync(new URL('../src/main.js', import.meta.url), 'utf8')
  assert.match(router, /import\('\.\.\/views\/ReturnScanView\.vue'\)/)
  assert.doesNotMatch(router, /import ReturnScanView from/)
  assert.match(router, /if \(to\.meta\.public\)/)
  assert.match(router, /if \(!permStore\.loaded\) permStore\.load\(\)/)
  assert.match(app, /skipDashboardShell/)
  assert.match(app, /DashboardShell/)
  assert.match(app, /isBarePublic/)
  assert.doesNotMatch(main, /main\.css/)
  assert.doesNotMatch(html, /fonts\.googleapis/)
  assert.match(vite, /cssCodeSplit:\s*false/)
})

test('returns queue keeps the dashboard sidebar, scanner stays kiosk', async () => {
  const { isReturnKioskPath, isClientFormPath, skipDashboardShell } = await import('../src/returnKiosk.js')
  assert.equal(isReturnKioskPath('/returns'), false)
  assert.equal(isReturnKioskPath('/returns?mp=wb'), false)
  assert.equal(isReturnKioskPath('/return/scan'), true)
  assert.equal(isReturnKioskPath('/return/batch/123'), true)
  assert.equal(isReturnKioskPath('/return/mp.abc.r'), true)
  assert.equal(isReturnKioskPath('/reshipment'), false)
  assert.equal(isClientFormPath('/reshipment/form'), true)
  assert.equal(isClientFormPath('/reshipment/form?t=abc'), true)
  assert.equal(isClientFormPath('/reshipment/confirm/tok'), true)
  assert.equal(isClientFormPath('/reshipment'), false)
  assert.equal(skipDashboardShell('/reshipment/form'), true)
  assert.equal(skipDashboardShell('/chats'), false)
})

