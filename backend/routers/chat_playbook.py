@router.get("")
def get_playbook(db: Session = Depends(get_db), current_user=Depends(get_current_user)):
    themes = db.execute(text("""
        SELECT theme_key, name, when_text, zone, action, note, sort_order, active
        FROM cx_chat_themes ORDER BY sort_order, name
    """)).mappings().all()
    variants = db.execute(text("""
        SELECT id, theme_key, branch_key, branch_label, body, sort_order, active,
               coalesce(mp,'') AS mp,
               coalesce(review_status, 'approved') AS review_status,
               coalesce(created_by, '') AS created_by,
               created_at,
               coalesce(source_chat_id, '') AS source_chat_id,
               coalesce(source_mp, '') AS source_mp,
               coalesce(updated_by, '') AS updated_by,
               updated_at
        FROM cx_chat_variants ORDER BY theme_key, mp, branch_key, sort_order, id
    """)).mappings().all()
    settings = db.execute(text(
        "SELECT key, value, descr FROM cx_chat_settings ORDER BY key"
    )).mappings().all()
    zone_rows = db.execute(text("""
        SELECT theme_key, mp, zone FROM cx_chat_theme_zones
    """)).mappings().all()
    zones_map: dict = {}
    for zr in zone_rows:
        zones_map.setdefault(zr["theme_key"], {})[zr["mp"]] = zr["zone"]

    by_theme = {}
    for v in variants:
        row = dict(v)
        if row.get("created_at") is not None:
            row["created_at"] = row["created_at"].isoformat()
        if row.get("updated_at") is not None:
            row["updated_at"] = row["updated_at"].isoformat()
        by_theme.setdefault(row["theme_key"], []).append(row)

    out_themes = []
    for t in themes:
        if t["theme_key"] == UNASSIGNED_THEME_KEY:
            continue
        td = dict(t)
        legacy = td.get("zone") if td.get("zone") in ZONES else "draft"
        per = zones_map.get(td["theme_key"], {})
        zones = {
            mp: (per.get(mp) if per.get(mp) in ZONES else legacy)
            for mp in BOT_MPS
        }
        td["zones"] = zones
        # zone = WB (обратная совместимость старых клиентов)
        td["zone"] = zones["wb"]
        td["variants"] = by_theme.get(td["theme_key"], [])
        out_themes.append(td)

    pending_count = db.execute(text("""
        SELECT count(*) FROM cx_chat_variants
        WHERE coalesce(review_status, 'approved') = 'pending'
    """)).scalar() or 0

    return {
        "themes": out_themes,
        "settings": [dict(s) for s in settings],
        "pending_count": int(pending_count),
    }


